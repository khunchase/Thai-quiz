function parse(raw: string): WordPart[] {
  return raw.split(' + ').map((part) => {
    const [thai, romanization, english] = part.split(':');
    return { thai, romanization, english };
  });
}

export const EXTRA_BREAKDOWNS: Record<string, WordPart[]> = Object.fromEntries(
  Object.entries(RAW).map(([thai, raw]) => [thai, parse(raw)])
);

/** Gives a word its extra breakdown when it doesn't already have one. */
export function withExtraBreakdown<T extends Word>(word: T): T {
  if (word.breakdown && word.breakdown.length >= 2) return word;
  const breakdown = EXTRA_BREAKDOWNS[word.thai];
  return breakdown ? { ...word, breakdown } : word;
}
